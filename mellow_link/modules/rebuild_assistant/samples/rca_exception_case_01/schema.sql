CREATE TABLE TB_ORDER (
    ORDER_NO        VARCHAR(20) PRIMARY KEY,
    CUSTOMER_NAME   VARCHAR(100) NOT NULL,
    STATUS_CD       VARCHAR(10) NOT NULL,
    URGENT_YN       CHAR(1) DEFAULT 'N',
    DEPT_CD         VARCHAR(20),
    HANDLER_ID      VARCHAR(50),
    ORDER_DATE      DATE NOT NULL,
    CREATED_AT      TIMESTAMP,
    UPDATED_AT      TIMESTAMP
);

CREATE TABLE TB_CODE (
    GROUP_CD        VARCHAR(50) NOT NULL,
    CODE_CD         VARCHAR(20) NOT NULL,
    CODE_NAME       VARCHAR(100) NOT NULL,
    PRIMARY KEY (GROUP_CD, CODE_CD)
);

CREATE TABLE TB_DEPT (
    DEPT_CD         VARCHAR(20) PRIMARY KEY,
    DEPT_NAME       VARCHAR(100) NOT NULL
);

CREATE TABLE TB_USER (
    USER_ID         VARCHAR(50) PRIMARY KEY,
    USER_NAME       VARCHAR(100) NOT NULL,
    USER_ROLE       VARCHAR(20),
    USER_DEPT       VARCHAR(20)
);
